        /// <summary>
        /// Elevation log round-trips through <see cref="ElevationFiles"/> (Elevation.txt). The handler is
        /// asymmetric — <see cref="ElevationFiles.Load"/> returns the raw lines while
        /// <see cref="ElevationFiles.CreateHeader"/> + <see cref="ElevationFiles.Append"/> write the file —
        /// so the re-save reconstructs the canonical header (timestamp + StartFix parsed back out of the
        /// golden) through the real writer and re-appends any post-column-header grid rows. A header-only
        /// golden (elevation logging off, the default) round-trips exactly.
        /// </summary>
        [Test]
        public void Elevation_RoundTrip_IsByteIdentical()
        {
            byte[] golden = LoadRequiredGolden("Elevation.txt");
            StageGolden(golden, "Elevation.txt");

            ElevationFiles.ElevationData data = ElevationFiles.Load(_fieldDir);
            List<string> raw = data.RawLines;

            Assert.That(raw, Is.Not.Empty,
                "Elevation golden contained no readable lines; cannot reconstruct via ElevationFiles.");

            DateTime timestamp = DateTime.ParseExact(
                raw[0], "yyyy-MMMM-dd hh:mm:ss tt", CultureInfo.InvariantCulture);

            int startFixIndex = raw.FindIndex(l => l.Trim() == "StartFix");
            bool startFixOk = startFixIndex >= 0 && startFixIndex < raw.Count - 1;
            Assert.That(startFixOk, Is.True,
                "Elevation golden is missing a 'StartFix' marker followed by a lat,lon line.");

            string[] originParts = raw[startFixIndex + 1].Split(',');
            double lat = double.Parse(originParts[0], CultureInfo.InvariantCulture);
            double lon = double.Parse(originParts[1], CultureInfo.InvariantCulture);
            var startFix = new AgOpenGPS.Core.Models.Wgs84(lat, lon);

            ElevationFiles.CreateHeader(_outDir, timestamp, startFix);

            // Re-append any elevation grid samples that follow the "Latitude,Longitude,..." column header,
            // using the same per-line newline CreateHeader's WriteLine emits so the file stays consistent.
            int columnHeaderIndex = raw.FindIndex(l => l.StartsWith("Latitude", StringComparison.Ordinal));
            if (columnHeaderIndex >= 0 && columnHeaderIndex < raw.Count - 1)
            {
                List<string> gridRows = raw.GetRange(
                    columnHeaderIndex + 1, raw.Count - columnHeaderIndex - 1);
                string gridText = string.Join(Environment.NewLine, gridRows) + Environment.NewLine;
                ElevationFiles.Append(_outDir, gridText);
            }

            byte[] saved = File.ReadAllBytes(Path.Combine(_outDir, "Elevation.txt"));
            Assert.That(saved, Is.EqualTo(golden));
        }

