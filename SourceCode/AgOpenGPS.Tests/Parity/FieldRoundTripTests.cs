// [XPLAT] migrated from net48 — see MIGRATION_DOCS/TRANSITION_MAP.md
//
// Field-file load -> save -> byte-compare parity suite (AAP §0.6.4 "FieldRoundTripTests").
//
// PROOF OBLIGATION
// ----------------
// The net48/WinForms -> net8.0/Avalonia migration must not let the field-file formats under
// SourceCode/GPS/IO/ drift, and must not let the cross-OS hazards of AAP §0.6.5 (end-of-line,
// culture/decimal-separator, path separators) corrupt a single byte. For every field artifact this
// fixture loads a golden file captured from the Windows/net48 baseline, stages it into a temporary
// field directory under the handler's REAL on-disk file name, drives the production AgOpenGPS.IO
// handler's Load then Save (re-emitting through the genuine serializer), reads the re-saved file back
// as RAW BYTES, and asserts it is byte-for-byte identical to the golden.
//
// WHY THE STATIC AgOpenGPS.IO HANDLERS (NOT FieldIoService)
// ---------------------------------------------------------
// The extracted AgOpenGPS.Services.FieldIoService orchestrator requires a heavy domain object graph
// (FormGPS / ApplicationCore collaborators) that cannot be assembled in a unit test. The static
// AgOpenGPS.IO.*Files handlers carry the actual serialization logic and are pure file-in / file-out,
// so they exercise the real production format directly and remain cleanly callable here.
//
// ENFORCING GOLDENS (final gate)
// ------------------------------
// The field goldens are committed under Parity/Golden/Field and the byte-contract is ENFORCED: each
// golden-consuming test calls LoadRequiredGolden, which FAILS (not Ignores) when its artifact is absent.
// A missing golden means contract C2 (field-file byte formats) is unproven, so the suite must surface
// red rather than green-with-skips. The goldens are byte-identical across windows / ubuntu / macos
// (including osx-arm64) because the Parity tree is pinned `-text` in .gitattributes (no CRLF<->LF
// normalization); full tri-OS execution evidence is recorded in MIGRATION_DOCS/PARITY_REPORT.md.
//
// This extends the round-trip byte-compare pattern proven in
// SourceCode/AgLibrary.Tests/Settings/XmlSettingsHandlerTests.cs, upgraded from File.ReadAllText to
// File.ReadAllBytes so the comparison is byte-exact rather than text-equivalent.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using AgOpenGPS.IO;
using NUnit.Framework;

namespace AgOpenGPS.Tests.Parity
{
    /// <summary>
    /// Byte-exact load -> save round-trip parity tests for the <c>SourceCode/GPS/IO/</c> field-file
    /// handlers. Every test stages a frozen golden, re-emits it through the production
    /// <see cref="AgOpenGPS.IO"/> serializer, and asserts the regenerated bytes equal the golden. The
    /// goldens are committed and the byte-contract is ENFORCED: a test FAILS (it does not self-skip) when
    /// its required golden is absent, so contract C2 cannot silently regress at the final gate.
    /// </summary>
    [TestFixture]
    public class FieldRoundTripTests
    {
        /// <summary>
        /// Per-test input directory: the golden is staged here under the handler's real on-disk file
        /// name so the production <c>Load</c> reads exactly what the baseline wrote.
        /// </summary>
        private string _fieldDir;

        /// <summary>
        /// Per-test output directory: the production <c>Save</c> re-emits here, isolated from the staged
        /// input so an append-style writer can never interleave with the staged golden bytes.
        /// </summary>
        private string _outDir;

        /// <summary>
        /// [XPLAT] Forces <see cref="CultureInfo.InvariantCulture"/> for the whole fixture so the only
        /// correct decimal separator is a period regardless of the host locale. The IO handlers already
        /// format/parse with <see cref="CultureInfo.InvariantCulture"/>; pinning invariant culture here
        /// makes any regression to culture-sensitive formatting (a comma-decimal locale such as de-DE or
        /// fr-FR on Linux/macOS — AAP §0.6.5) surface deterministically. Mirrors the sibling Parity fixtures.
        /// </summary>
        [OneTimeSetUp]
        public void ForceInvariantCulture()
        {
            CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
            CultureInfo.CurrentUICulture = CultureInfo.InvariantCulture;
        }

        /// <summary>
        /// Creates fresh, uniquely named input and output directories under
        /// <see cref="Path.GetTempPath"/> so no test ever touches a real field location and parallel
        /// test runs never collide.
        /// </summary>
        [SetUp]
        public void CreateTempDirectories()
        {
            _fieldDir = Path.Combine(
                Path.GetTempPath(), "AgOpenGPS_FieldParity_in_" + Guid.NewGuid().ToString("N"));
            _outDir = Path.Combine(
                Path.GetTempPath(), "AgOpenGPS_FieldParity_out_" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(_fieldDir);
            Directory.CreateDirectory(_outDir);
        }

        /// <summary>
        /// Removes the per-test temp directories. Cleanup is best-effort: a leaked temp directory must
        /// never turn a parity assertion red.
        /// </summary>
        [TearDown]
        public void RemoveTempDirectories()
        {
            TryDeleteDirectory(_fieldDir);
            TryDeleteDirectory(_outDir);
        }

        // =====================================================================================
        // Phase B — one byte-compare round-trip [Test] per field artifact.
        // =====================================================================================

        /// <summary>Boundary rings round-trip through <see cref="BoundaryFiles"/> (Boundary.txt, header <c>$Boundary</c>).</summary>
        [Test]
        public void Boundary_RoundTrip_IsByteIdentical()
        {
            byte[] golden = LoadRequiredGolden("Boundary.txt");
            StageGolden(golden, "Boundary.txt");

            // Empty/edge case is handled naturally: a "$Boundary\n" golden loads to an empty list and
            // re-saves to "$Boundary\n", so a minimal golden still round-trips.
            List<CBoundaryList> boundaries = BoundaryFiles.Load(_fieldDir);
            BoundaryFiles.Save(_outDir, boundaries);

            byte[] saved = File.ReadAllBytes(Path.Combine(_outDir, "Boundary.txt"));
            Assert.That(saved, Is.EqualTo(golden));
        }

