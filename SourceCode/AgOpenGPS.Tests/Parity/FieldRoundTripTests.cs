        /// </summary>
        [Test]
        public void Flags_RoundTrip_IsByteIdentical()
        {
            byte[] golden = LoadRequiredGolden("Flags.txt");
            StageGolden(golden, "Flags.txt");

            List<CFlag> flags = FlagsFiles.Load(_fieldDir);
            FlagsFiles.Save(_outDir, flags);

            byte[] saved = File.ReadAllBytes(Path.Combine(_outDir, "Flags.txt"));
