        // =====================================================================================
        // Helpers (cross-OS golden resolution, staging, invariant-culture and cleanup utilities).
        // =====================================================================================

        /// <summary>
        /// [XPLAT] Resolves a Field golden next to the test assembly (copied there by the
        /// <c>AgOpenGPS.Tests.csproj</c> <c>Parity\Golden\**\*</c> rule) using
        /// <see cref="TestContext.CurrentContext"/>.<c>TestDirectory</c> and <see cref="Path.Combine"/>
        /// so resolution is correct and case-stable on Windows, Linux and macOS. The field goldens are a
        /// committed, ENFORCING byte-contract: when the artifact is absent the test FAILS (it does not
        /// self-skip). This is the final-gate enforcement of behavior-frozen contract C2 (field-file byte
        /// formats) — a missing golden means the field byte-contract is unproven, which must surface red.
        /// </summary>
        /// <param name="fileName">The golden file name within <c>Parity/Golden/Field</c>.</param>
        /// <returns>The raw golden bytes.</returns>
        private static byte[] LoadRequiredGolden(string fileName)
        {
            string path = Path.Combine(
                TestContext.CurrentContext.TestDirectory, "Parity", "Golden", "Field", fileName);

            if (!File.Exists(path))
            {
                Assert.Fail(
                    $"Required field golden is missing: {path}. The field byte-contract (AAP contract C2) " +
                    "cannot be proven without it. Capture the baseline artifact and commit it under " +
                    "SourceCode/AgOpenGPS.Tests/Parity/Golden/Field/.");
            }

            return File.ReadAllBytes(path);
        }

        /// <summary>
        /// Writes the golden bytes verbatim into the per-test input directory under the handler's real
        /// on-disk field-file name, so the production <c>Load</c> reads exactly the captured baseline bytes.
        /// </summary>
        /// <param name="goldenBytes">The golden content to stage.</param>
        /// <param name="onDiskFileName">The real field-file name the handler reads (e.g. <c>TrackLines.txt</c>).</param>
        /// <returns>The full staged path (built with <see cref="Path.Combine"/>).</returns>
        private string StageGolden(byte[] goldenBytes, string onDiskFileName)
        {
            string path = Path.Combine(_fieldDir, onDiskFileName);
            File.WriteAllBytes(path, goldenBytes);
            return path;
        }

        /// <summary>
        /// Asserts <paramref name="sampleValue"/> appears in <paramref name="textBytes"/> in its
        /// <see cref="CultureInfo.InvariantCulture"/> (period decimal) form. Under a comma-decimal host
        /// locale the value would serialize as "53,12" and the period form would be ABSENT, so a
        /// regression to culture-sensitive formatting fails this assertion (AAP §0.6.5).
        /// </summary>
        private static void AssertInvariantPeriodFormat(byte[] textBytes, double sampleValue)
        {
            string text = System.Text.Encoding.UTF8.GetString(textBytes);
            string invariant = sampleValue.ToString(CultureInfo.InvariantCulture);
            Assert.That(text.Contains(invariant, StringComparison.Ordinal), Is.True,
                $"Expected InvariantCulture period-decimal form '{invariant}' in the serialized output.");
        }

        /// <summary>
        /// Returns the first line of a UTF-8 byte buffer (newline excluded, trailing CR trimmed) without
        /// allocating intermediate line arrays — used to recover a writer-emitted timestamp header line.
        /// </summary>
        private static string FirstLine(byte[] utf8Bytes)
        {
            string text = System.Text.Encoding.UTF8.GetString(utf8Bytes);
            int newlineIndex = text.IndexOf('\n');
            string line = newlineIndex >= 0 ? text.Substring(0, newlineIndex) : text;
            return line.TrimEnd('\r');
        }

        /// <summary>
        /// Deletes a temp directory tree, swallowing IO failures so cleanup never fails a parity result.
        /// </summary>
        private static void TryDeleteDirectory(string directory)
        {
            try
            {
                if (!string.IsNullOrEmpty(directory) && Directory.Exists(directory))
                {
                    Directory.Delete(directory, true);
                }
            }
            catch (IOException)
            {
                // Best-effort cleanup; a leaked temp directory must never break a test result.
            }
            catch (UnauthorizedAccessException)
            {
                // Same rationale: a permission hiccup during cleanup is not a parity failure.
            }
        }
